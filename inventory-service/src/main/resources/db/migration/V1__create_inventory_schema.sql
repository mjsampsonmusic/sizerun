CREATE TABLE store (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  VARCHAR(10)  NOT NULL UNIQUE,
    name  VARCHAR(100) NOT NULL,
    city  VARCHAR(100) NOT NULL
);

-- One row per size of each style and color, such as Tempo Runner, Midnight Navy, size 9.5
CREATE TABLE product (
    sku          VARCHAR(32)  PRIMARY KEY,
    style_code   VARCHAR(16)  NOT NULL,
    style_name   VARCHAR(100) NOT NULL,
    color        VARCHAR(50)  NOT NULL,
    us_size      NUMERIC(3, 1) NOT NULL CHECK (us_size > 0),
    price_cents  INTEGER      NOT NULL CHECK (price_cents >= 0),
    UNIQUE (style_code, us_size)
);

-- Units on hand per store. The CHECK is a last line of defense: stock can never go negative.
CREATE TABLE stock (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id  BIGINT      NOT NULL REFERENCES store (id),
    sku       VARCHAR(32) NOT NULL REFERENCES product (sku),
    quantity  INTEGER     NOT NULL CHECK (quantity >= 0),
    UNIQUE (store_id, sku)
);

-- order_ref is UNIQUE so a retried order can never reserve stock twice
CREATE TABLE reservation (
    id           UUID        PRIMARY KEY,
    order_ref    VARCHAR(64) NOT NULL UNIQUE,
    store_id     BIGINT      NOT NULL REFERENCES store (id),
    status       VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE', 'RELEASED')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    released_at  TIMESTAMPTZ
);

CREATE TABLE reservation_line (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id    UUID        NOT NULL REFERENCES reservation (id) ON DELETE CASCADE,
    sku               VARCHAR(32) NOT NULL REFERENCES product (sku),
    quantity          INTEGER     NOT NULL CHECK (quantity > 0),
    unit_price_cents  INTEGER     NOT NULL CHECK (unit_price_cents >= 0)
);

CREATE INDEX reservation_line_reservation_idx ON reservation_line (reservation_id);
